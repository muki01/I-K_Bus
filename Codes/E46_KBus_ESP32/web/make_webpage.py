"""Builds WebPage.h from index.html.

The ESP32 keeps the web page gzip-compressed in flash and sends it as it is: the phone unpacks it. That makes
the page about a third of its size and costs the ESP32 nothing.

    python make_webpage.py           write ../WebPage.h from index.html
    python make_webpage.py --check   only check that ../WebPage.h holds exactly index.html (used by the CI build)
"""
import gzip
import hashlib
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
PAGE = HERE / 'index.html'
HEADER = HERE.parent / 'WebPage.h'

TEMPLATE = '''// -----------------------------------------------------------------------------
// WebPage.h - the web interface served by the ESP32
//
// GENERATED from web/index.html by web/make_webpage.py - do not edit this file.
// To change the page, edit web/index.html and run:  python make_webpage.py
//
// The page is stored gzip-compressed ({gz} bytes instead of {raw}) and sent as
// it is; the phone unpacks it. It needs no internet connection: everything,
// including the drawing of the car, is inside the page. The buttons are not part
// of the page - it asks the ESP32 for them (Commands.h).
// -----------------------------------------------------------------------------

#ifndef WEB_PAGE_H
#define WEB_PAGE_H

// Changes whenever the page changes; the phone keeps the page in its cache and
// only downloads it again when this value is different.
#define WEB_PAGE_ETAG "\\"{etag}\\""

const size_t WEB_PAGE_GZ_SIZE = {gz};

const uint8_t WEB_PAGE_GZ[] PROGMEM = {{
{data}
}};

#endif
'''


def read_header():
    text = HEADER.read_text(encoding='utf-8')
    body = text[text.index('WEB_PAGE_GZ[] PROGMEM = {') + 25:text.rindex('};')]
    return bytes(int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{2})', body))


def main():
    html = PAGE.read_bytes()
    if '--check' in sys.argv:
        stored = gzip.decompress(read_header())
        if stored != html:
            sys.exit('WebPage.h does not match web/index.html - run python make_webpage.py in Codes/E46_KBus_ESP32/web')
        print(f'WebPage.h matches web/index.html ({len(html)} bytes)')
        return
    packed = gzip.compress(html, compresslevel=9, mtime=0)
    rows = [', '.join(f'0x{b:02x}' for b in packed[i:i + 16]) for i in range(0, len(packed), 16)]
    HEADER.write_text(TEMPLATE.format(gz=len(packed), raw=len(html), etag=hashlib.sha1(html).hexdigest()[:12],
                                      data=',\n'.join('  ' + r for r in rows)), encoding='utf-8', newline='\n')
    print(f'WebPage.h written: {len(html)} bytes of HTML, {len(packed)} bytes gzip')


if __name__ == '__main__':
    main()
